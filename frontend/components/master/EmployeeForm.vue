<template>
  <UModal
    v-model:open="store.showModal"
    dismissible
    @update:open="(val: boolean) => { if (!val) store.closeModal() }"
    :ui="{ content: 'w-[calc(100vw-2rem)] sm:w-full sm:max-w-2xl max-h-[90vh] flex flex-col bg-white dark:bg-gray-900 border border-gray-200 dark:border-gray-800 rounded-2xl shadow-xl overflow-hidden' }"
  >
    <template #content>
      <UForm :state="store.form" @submit.prevent="store.handleSubmit">
        <div class="relative bg-[var(--bg-main)] rounded-xl shadow-2xl flex flex-col max-h-[90vh] border border-[var(--border-main)] transition-colors duration-300">

          <!-- Header -->
          <div class="px-4 sm:px-6 py-4 border-b border-[var(--border-main)] bg-[var(--bg-surface)] rounded-t-xl flex justify-between items-center transition-colors duration-300">
            <div class="flex items-center gap-3">
              <UIcon name="i-heroicons-user-group" class="text-primary-500 text-2xl" />
              <h3 class="text-lg font-bold text-[var(--text-main)]">
                {{ store.isEditing ? 'Edit Employee' : 'Add New Employee' }}
              </h3>
            </div>
            <button
              type="button"
              @click="store.closeModal"
              class="text-gray-400 hover:text-gray-600 dark:hover:text-gray-200 transition-colors p-1 rounded-lg focus:outline-none"
              :aria-label="t('masterData.company.close')"
            >
              <UIcon name="i-heroicons-x-mark" class="text-2xl" />
            </button>
          </div>

          <!-- Body -->
          <div class="p-4 sm:p-6 overflow-y-auto space-y-4">
            <!-- Error Message -->
            <UAlert
              v-if="store.errorMsg"
              color="error"
              variant="soft"
              :title="store.errorMsg"
              icon="i-heroicons-exclamation-circle"
              class="mb-4"
            />

            <!-- Basic Info -->
            <div class="space-y-4">
              <h4 class="text-sm tracking-widertext-primary-500 font-bold border-b border-[var(--border-main)] pb-2"> {{ t('auditActivityPlan.view.basicInfo') }} </h4>

              <div class="grid grid-cols-1 gap-4 md:grid-cols-2">
                <UFormField :label="t('masterData.employee.form.code')" size="lg">
                  <!-- Read-only: generated by the backend on create; preview shown in create mode -->
                  <UInput
                    :model-value="employeeCodeDisplay"
                    type="text"
                    :placeholder="t('masterData.employee.autoGenerated')"
                    disabled
                    class="w-full"
                  />
                </UFormField>

                <UFormField :label="t('masterData.employee.form.fullName')" size="lg">
                  <UInput
                    v-model="store.form.full_name"
                    type="text"
                    :placeholder="t('masterData.employee.form.fullNamePlaceholder')"
                    required
                  />
                </UFormField>

                <UFormField :label="t('masterData.employee.form.email')" size="lg">
                  <UInput
                    v-model="store.form.email"
                    type="email"
                    placeholder="email@example.com"
                    required
                  />
                </UFormField>

                <UFormField :label="t('masterData.employee.columns.phone')" size="lg">
                  <!-- Digits only: input is normalised in onPhoneInput -->
                  <UInput
                    ref="phoneInputRef"
                    :model-value="store.form.phone"
                    type="tel"
                    inputmode="numeric"
                    placeholder="e.g. 081234567890"
                    @update:model-value="onPhoneInput"
                  />
                </UFormField>

                <UFormField :label="t('masterData.employee.form.joinDate')" size="lg">
                  <AppDatePicker
                    v-model="store.form.join_date"
                    required
                  />
                </UFormField>
              </div>

              <UFormField :label="t('masterData.employee.columns.status')" size="lg">
                <div class="flex items-center gap-4">
                  <label class="flex items-center gap-2 cursor-pointer">
                    <input
                      type="radio"
                      :checked="store.form.is_active"
                      @change="store.form.is_active = true"
                      class="w-4 h-4 text-primary-600"
                    />
                    <span>{{ t('masterData.employee.active') }}</span>
                  </label>
                  <label class="flex items-center gap-2 cursor-pointer">
                    <input
                      type="radio"
                      :checked="!store.form.is_active"
                      @change="store.form.is_active = false"
                      class="w-4 h-4 text-error-600"
                    />
                    <span>{{ t('masterData.employee.inactive') }}</span>
                  </label>
                </div>
              </UFormField>
            </div>

            <!-- Organization -->
            <div class="space-y-4 pt-4">
              <h4 class="text-sm tracking-widertext-primary-500 font-bold border-b border-[var(--border-main)] pb-2"> {{ t('siteGenerator.steps.organization') }} </h4>

              <div class="grid grid-cols-1 gap-4 md:grid-cols-2">
                <UFormField :label="t('masterData.department.companyId')" size="lg">
                  <USelectMenu
                    v-model="store.form.company_id"
                    :items="options.companyOptions"
                    value-key="value"
                    :loading="options.loading"
                    :placeholder="t('masterData.department.companyIdPlaceholder')"
                    class="w-full"
                    required
                  />
                </UFormField>

                <UFormField :label="t('masterData.employee.form.department')" size="lg">
                  <USelectMenu
                    v-model="store.form.department_id"
                    :items="options.departmentOptions"
                    value-key="value"
                    :loading="options.loading"
                    :placeholder="t('settings.profile.selectDepartment')"
                    class="w-full"
                    required
                  />
                </UFormField>

                <UFormField :label="t('masterData.employee.form.jobRole')" size="lg">
                  <USelectMenu
                    v-model="store.form.job_role_id"
                    :items="options.jobRoleOptions"
                    value-key="value"
                    :loading="options.loading"
                    :placeholder="t('masterData.employee.form.jobRolePlaceholder')"
                    class="w-full"
                    required
                  />
                </UFormField>

                <UFormField :label="t('masterData.employee.form.workLocation')" size="lg">
                  <USelectMenu
                    v-model="store.form.work_location_id"
                    :items="workLocationItems"
                    value-key="value"
                    :loading="options.loading"
                    :clear="true"
                    :placeholder="t('masterData.employee.form.workLocationPlaceholder')"
                    class="w-full"
                    @update:model-value="onWorkLocationChange"
                  />
                </UFormField>

                <UFormField :label="t('masterData.employee.form.manager')" size="lg">
                  <USelectMenu
                    v-model="store.form.manager_id"
                    :items="managerItems"
                    value-key="value"
                    :loading="options.loading"
                    :clear="true"
                    :placeholder="t('masterData.employee.form.managerPlaceholder')"
                    class="w-full"
                    @update:model-value="onManagerChange"
                  />
                </UFormField>
              </div>
            </div>

            <!-- Address -->
            <div class="space-y-4 pt-4">
              <h4 class="text-sm tracking-widertext-gray-500 font-bold border-b border-[var(--border-main)] pb-2"> {{ t('masterData.location.columns.address') }} </h4>

              <UFormField :label="t('masterData.employee.form.address')" size="lg">
                <UTextarea
                  v-model="store.form.residence_address"
                  :placeholder="t('masterData.location.fieldAddressPlaceholder')"
                  :rows="2"
                  autoresize
                />
              </UFormField>

              <div class="grid grid-cols-1 gap-4 md:grid-cols-3">
                <UFormField :label="t('masterData.location.columns.city')" size="lg">
                  <UInput
                    v-model="store.form.residence_city"
                    type="text"
                    :placeholder="t('masterData.location.columns.city')"
                  />
                </UFormField>

                <UFormField :label="t('masterData.location.fieldProvince')" size="lg">
                  <UInput
                    v-model="store.form.residence_province"
                    type="text"
                    :placeholder="t('masterData.location.fieldProvince')"
                  />
                </UFormField>

                <UFormField :label="t('masterData.location.fieldPostalCode')" size="lg">
                  <UInput
                    v-model="store.form.residence_postal_code"
                    type="text"
                    :placeholder="t('masterData.employee.form.postalCodePlaceholder')"
                  />
                </UFormField>
              </div>
            </div>
          </div>

          <!-- Footer -->
          <div class="px-6 py-4 bg-[var(--bg-surface)] border-t border-[var(--border-main)] rounded-b-xl flex justify-end gap-3">
            <UButton
              :label="t('masterData.employee.form.cancel')"
              color="neutral"
              variant="soft"
              type="button"
              @click="store.closeModal"
            />
            <UButton
              :label="store.isEditing ? 'Update' : 'Create'"
              color="primary"
              :loading="store.loading"
              type="submit"
            />
          </div>
        </div>
      </UForm>
    </template>
  </UModal>
</template>

<script setup lang="ts">
import { useEmployeeStore } from '~/stores/employee'
import { useMasterOptionsStore } from '~/stores/master-options'
import { useI18n } from '~/composables/useI18n'

const store = useEmployeeStore()
const options = useMasterOptionsStore()
const { t } = useI18n()

// Strip anything that is not a digit as the user types or pastes.
const phoneInputRef = ref<{ inputRef?: HTMLInputElement | null } | null>(null)

const onPhoneInput = (val: string | number | null | undefined) => {
  const digits = store.normalizePhone(val == null ? '' : String(val))
  store.form.phone = digits

  // If the stored value did not change (e.g. "0812" + "h"), Vue will not
  // re-patch the native input, so the typed letter stays visible. Sync the
  // DOM directly and keep the caret where the user was typing.
  const el = phoneInputRef.value?.inputRef
  if (el && el.value !== digits) {
    const caret = el.selectionStart ?? el.value.length
    const digitsBeforeCaret = store.normalizePhone(el.value.slice(0, caret)).length
    el.value = digits
    el.setSelectionRange(digitsBeforeCaret, digitsBeforeCaret)
  }
}

// Optional relations get an explicit empty choice so they can be cleared again.
const noneOption = { label: '— None —', value: '__none__' }

const onWorkLocationChange = (val: any) => {
  if (!val || val === '__none__') {
    store.form.work_location_id = ''
  }
}

const onManagerChange = (val: any) => {
  if (!val || val === '__none__') {
    store.form.manager_id = ''
  }
}

// Edit shows the saved code; create shows the backend preview (or a loading/fallback text).
const employeeCodeDisplay = computed(() => {
  if (store.isEditing) return store.form.employee_code
  if (store.nextEmployeeCodeLoading) return t('masterData.employee.codeLoading')
  if (store.nextEmployeeCodeFailed || !store.nextEmployeeCode) return t('masterData.employee.codeUnavailable')
  return store.nextEmployeeCode
})

const workLocationItems = computed(() => [noneOption, ...options.locationOptions])

// An employee cannot be their own manager.
const managerItems = computed(() => [
  noneOption,
  ...options.employeeOptions.filter((o) => o.value !== store.editingId)
])

// Load the reference lists the first time the modal is opened.
watch(
  () => store.showModal,
  (open) => {
    if (open) options.fetchAll()
  },
  { immediate: true }
)
</script>
